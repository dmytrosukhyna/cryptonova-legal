ga = math.pi * (3 - math.sqrt(5))
bits = bytearray((N + 7) // 8); land = 0
for i in range(N):
    y = 1 - 2 * (i + .5) / N; lat = math.degrees(math.asin(y)); lon = math.degrees((i * ga) % (2 * math.pi)) - 180
    isl = lat < -68 or any(inside(lon, lat, p) for p in P.values())
    if isl: bits[i >> 3] |= 1 << (i & 7); land += 1
print(json.dumps({"n": N, "land": land, "mask": base64.b64encode(bytes(bits)).decode()}))
